"""Frozen domain vocabulary shared by API, domain services and the frontend contract."""

from __future__ import annotations

from enum import StrEnum


class TelemetryEventType(StrEnum):
    # The spec's SQL comment calls the usage event AI_TOKENS_USED; USAGE_METERED is the
    # canonical name across SDK/API/DB and maps 1:1 to that concept.
    TOS_ACCEPTED = "TOS_ACCEPTED"
    SESSION_AUTH = "SESSION_AUTH"
    ASSET_DELIVERED = "ASSET_DELIVERED"
    USAGE_METERED = "USAGE_METERED"
    AI_GENERATION = "AI_GENERATION"
    # Server-only: Sentinel ALLOW/VETO verdicts on the SENTINEL-AUDIT chain.
    SENTINEL_VERDICT = "SENTINEL_VERDICT"


class DisputeStage(StrEnum):
    INQUIRY = "INQUIRY"
    CHARGEBACK = "CHARGEBACK"
    PRE_ARBITRATION = "PRE_ARBITRATION"
    ARBITRATION = "ARBITRATION"
    RESOLVED = "RESOLVED"
    CLOSED = "CLOSED"


class DisputeChannel(StrEnum):
    INTERNAL = "INTERNAL"
    EXTERNAL = "EXTERNAL"


class DisputeReason(StrEnum):
    MERCHANDISE_OR_SERVICE_NOT_RECEIVED = "MERCHANDISE_OR_SERVICE_NOT_RECEIVED"
    MERCHANDISE_OR_SERVICE_NOT_AS_DESCRIBED = "MERCHANDISE_OR_SERVICE_NOT_AS_DESCRIBED"
    UNAUTHORIZED = "UNAUTHORIZED"
    OTHER = "OTHER"


class DisputeStatus(StrEnum):
    OPEN = "OPEN"
    WAITING_FOR_SELLER_RESPONSE = "WAITING_FOR_SELLER_RESPONSE"
    UNDER_REVIEW = "UNDER_REVIEW"
    RESOLVED = "RESOLVED"
    CLOSED = "CLOSED"


class RecommendedAction(StrEnum):
    DEFLECT_INQUIRY = "DEFLECT_INQUIRY"
    MAKE_OFFER = "MAKE_OFFER"
    ACCEPT_CLAIM = "ACCEPT_CLAIM"
    PROVIDE_EVIDENCE = "PROVIDE_EVIDENCE"
    MONITOR = "MONITOR"


class DisputeAction(StrEnum):
    SEND_MESSAGE = "SEND_MESSAGE"
    MAKE_OFFER = "MAKE_OFFER"
    ACCEPT_CLAIM = "ACCEPT_CLAIM"
    PROVIDE_EVIDENCE = "PROVIDE_EVIDENCE"
    ESCALATE = "ESCALATE"
    APPEAL = "APPEAL"


class ActionStatus(StrEnum):
    EXECUTED = "EXECUTED"
    FAILED = "FAILED"
    SKIPPED = "SKIPPED"


class WebhookEventType(StrEnum):
    CUSTOMER_DISPUTE_CREATED = "CUSTOMER.DISPUTE.CREATED"
    CUSTOMER_DISPUTE_UPDATED = "CUSTOMER.DISPUTE.UPDATED"
    CUSTOMER_DISPUTE_RESOLVED = "CUSTOMER.DISPUTE.RESOLVED"
